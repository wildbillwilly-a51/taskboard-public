import { isLocalVisualDatabase } from "./helpers/visual-database";
import assert from "node:assert/strict";
import test from "node:test";
import { randomUUID } from "node:crypto";
import { mkdtemp, mkdir, writeFile, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { getPool } from "../src/lib/db";
import { ensureDatabaseReady } from "../src/lib/taskboard-store";
import { getPublicTaskFile, getPublicTaskWorkspace, manageTaskShare } from "../src/lib/public-task-share-store";
import type { TaskboardUserIdentity } from "../src/lib/taskboard-request";
test("public share isolation, updates, publication authority and permanent lifecycle revocation", { skip: process.env.TASKBOARD_PUBLIC_SHARE_DB_TEST !== "1", timeout: 120000 }, async () => {
    const url = new URL(process.env.DATABASE_URL!);
    assert.ok(isLocalVisualDatabase(url), "Use an explicitly isolated local visual-test database.");
    await ensureDatabaseReady();
    const pool = getPool()!;
    process.env.TASKBOARD_PUBLIC_SHARES_ENABLED = "true";
    const ids = Array.from({ length: 18 }, () => randomUUID()), [owner, other, admin, board, foreignBoard, root, child, sibling, note, privateNote, fileId, noteFileId, checklist, workingNote, team, teamBoard, teamManager, teamEditor] = ids;
    const user: TaskboardUserIdentity = { id: owner, email: `${owner}@example.test`, displayName: "Publisher", authMode: "authelia", role: "standard" };
    const temp = await mkdtemp(path.join(os.tmpdir(), "taskboard-public-share-")), cwd = process.cwd();
    try {
        for (const [id, role] of [[owner, "standard"], [other, "standard"], [admin, "admin"], [teamManager, "standard"], [teamEditor, "standard"]])
            await pool.query("INSERT INTO users(id,email,display_name,role) VALUES($1,$2,'Test user',$3)", [id, `${id}@example.test`, role]);
        await pool.query("INSERT INTO boards(id,owner_user_id,title,personal_visibility) VALUES($1,$2,'Published board','private'),($3,$4,'Foreign board','private')", [board, owner, foreignBoard, other]);
        const task = async (id: string, parent: string | null, title: string, b = board) => pool.query("INSERT INTO tasks(id,board_id,parent_task_id,title,status,sort_order,summary) VALUES($1,$2,$3,$4,'todo',1000,$5)", [id, b, parent, title, parent ? "" : "Root summary"]);
        await task(root, null, "Published root");
        await task(child, root, "Child work");
        await task(sibling, null, "PRIVATE SIBLING");
        await pool.query("INSERT INTO notes(id,owner_user_id,title,content_json,content_version) VALUES($1,$2,'Owned runbook',$3,1),($4,$5,'PRIVATE NOTE',$6,1)", [note, owner, JSON.stringify([{ type: "paragraph", content: [{ type: "text", text: "Public runbook", styles: {} }] }]), privateNote, other, JSON.stringify([{ type: "paragraph", content: [{ type: "text", text: "HIDDEN CONTENT", styles: {} }] }])]);
        await pool.query("INSERT INTO note_task_links(note_id,task_id) VALUES($1,$3),($2,$3)", [note, privateNote, root]);
        await pool.query("INSERT INTO checklist_items(id,task_id,label,sort_order) VALUES($1,$2,'Preflight',1000)", [checklist, root]);
        await pool.query("INSERT INTO task_notes(id,board_id,task_id,body,created_by_user_id) VALUES($1,$2,$3,'Working update',$4)", [workingNote, board, root, owner]);
        const deny = await manageTaskShare({ ...user, id: admin, role: "admin" }, root, "status");
        assert.equal(deny.allowed, false, "Global admin is not the personal-board publisher");
        assert.equal((await manageTaskShare({ ...user, id: other }, root, "status")).allowed, false);
        const created = await manageTaskShare(user, root, "create", "America/Chicago");
        assert.ok(created.url);
        const token = created.url.split("/").at(-1)!;
        const first = await getPublicTaskWorkspace(token, "https://taskboard.test");
        assert.equal(first.task.subtasks[0].title, "Child work");
        assert.equal(first.notes.length, 1);
        assert.equal(first.task.checklist.length, 1);
        assert.doesNotMatch(JSON.stringify(first), /PRIVATE|HIDDEN|DESCENDANT|owner_user_id|board_id/);
        assert.equal((await pool.query("SELECT token_hash FROM task_public_shares WHERE task_id=$1 AND revoked_at IS NULL", [root])).rows[0].token_hash.includes(token), false);
        await pool.query("UPDATE checklist_items SET is_done=true WHERE id=$1", [checklist]);
        const second = await getPublicTaskWorkspace(token, "https://taskboard.test");
        assert.notEqual(first.revision, second.revision);
        assert.equal(second.task.checklist[0].done, true);
        const complex = JSON.stringify([{ type: "paragraph", content: Array.from({ length: 10001 }, () => ({ type: "text", text: "x", styles: {} })) }]);
        await pool.query("UPDATE notes SET content_json=$2,content_version=content_version+1 WHERE id=$1", [note, complex]);
        const projected = await getPublicTaskWorkspace(token, "https://taskboard.test");
        assert.equal(projected.task.title, "Published root");
        assert.match(JSON.stringify(projected.notes[0].content), /cannot be displayed/);
        await pool.query("UPDATE notes SET content_json=jsonb_build_array(jsonb_build_object('type','paragraph','content',jsonb_build_array(jsonb_build_object('type','text','text',repeat('x',1000000),'styles','{}'::jsonb)))) WHERE id=$1", [note]);
        assert.match(JSON.stringify((await getPublicTaskWorkspace(token, "https://taskboard.test")).notes[0].content), /cannot be displayed/);
        await pool.query("UPDATE notes SET content_json='[]',content_version=content_version+1 WHERE id=$1", [note]);
        const budgetNotes = Array.from({ length: 30 }, () => randomUUID());
        await pool.query("INSERT INTO notes(id,owner_user_id,title,content_json) SELECT id,$2,'Budget note',jsonb_build_array(jsonb_build_object('type','paragraph','content',jsonb_build_array(jsonb_build_object('type','text','text',repeat('x',220000),'styles','{}'::jsonb)))) FROM unnest($1::uuid[]) id", [budgetNotes, owner]);
        await pool.query("INSERT INTO note_task_links(note_id,task_id) SELECT id,$2 FROM unnest($1::uuid[]) id", [budgetNotes, root]);
        const budgeted = await getPublicTaskWorkspace(token, "https://taskboard.test");
        assert.equal(budgeted.notes.length, 31);
        assert.ok(Buffer.byteLength(JSON.stringify(budgeted)) < 3 * 1024 * 1024);
        assert.match(JSON.stringify(budgeted.notes), /cannot be displayed/);
        await pool.query("DELETE FROM notes WHERE id=ANY($1::uuid[])", [budgetNotes]);
        await pool.query("UPDATE task_notes SET body=repeat('x',1000000) WHERE id=$1",[workingNote]);
        const primary=randomUUID();
        await pool.query("INSERT INTO task_notes(id,board_id,task_id,note_type,body) VALUES($1,$2,$3,'primary',repeat('x',1000000))",[primary,board,root]);
        await pool.query("UPDATE tasks SET summary=repeat('x',1000000),next_action=repeat('x',1000000) WHERE id=$1",[root]);
        const oversizedText=await getPublicTaskWorkspace(token,"https://taskboard.test");
        assert.equal(oversizedText.task.title,"Published root");
        assert.match(oversizedText.task.summary,/cannot be displayed/);assert.match(oversizedText.task.nextAction!,/cannot be displayed/);
        assert.match(oversizedText.task.primaryNote!.body,/cannot be displayed/);assert.match(oversizedText.task.notes[0].body,/cannot be displayed/);
        const logs=Array.from({length:30},()=>randomUUID());
        await pool.query("INSERT INTO task_notes(id,board_id,task_id,body) SELECT id,$2,$3,repeat('x',220000) FROM unnest($1::uuid[]) id",[logs,board,root]);
        const manyLogs=await getPublicTaskWorkspace(token,"https://taskboard.test");assert.equal(manyLogs.task.notes.length,31);assert.ok(Buffer.byteLength(JSON.stringify(manyLogs))<3*1024*1024);
        await pool.query("DELETE FROM task_notes WHERE id=ANY($1::uuid[])",[[...logs,primary]]);
        await pool.query("UPDATE tasks SET summary='Root summary',next_action='' WHERE id=$1",[root]);
        await pool.query("UPDATE task_notes SET body='Changed working note' WHERE id=$1", [workingNote]);
        assert.notEqual(second.revision, (await getPublicTaskWorkspace(token, "https://taskboard.test")).revision);
        const stored = `${board}/${root}/${fileId}`;
        await mkdir(path.join(temp, "uploads/task-attachments", board, root), { recursive: true });
        await writeFile(path.join(temp, "uploads/task-attachments", stored), "%PDF-1.4\nSynthetic PDF");
        await pool.query("INSERT INTO task_attachments(id,task_id,board_id,uploaded_by_user_id,original_name,display_name,stored_name,mime_type,size_bytes) VALUES($1,$2,$3,$4,'plan.pdf','plan.pdf',$5,'application/pdf',23)", [fileId, root, board, owner, stored]);
        await mkdir(path.join(temp, "uploads/note-attachments", note), { recursive: true });
        await writeFile(path.join(temp, "uploads/note-attachments", note, noteFileId), "private note file");
        await pool.query("INSERT INTO note_attachments(id,note_id,original_name,stored_name,mime_type,size_bytes) VALUES($1,$2,'runbook.txt',$3,'text/plain',17)", [noteFileId, note, `${note}/${noteFileId}`]);
        process.chdir(temp);
        assert.equal((await getPublicTaskFile(token, "task", fileId)).preview, "pdf");
        assert.equal((await getPublicTaskFile(token, "note", noteFileId)).name, "runbook.txt");
        await assert.rejects(getPublicTaskFile(token, "task", noteFileId));
        await assert.rejects(getPublicTaskFile(token, "note", fileId));
        await assert.rejects(getPublicTaskFile(token, "task", sibling));
        process.chdir(cwd);
        const rotated = await manageTaskShare(user, root, "replace");
        await assert.rejects(getPublicTaskWorkspace(token, "https://taskboard.test"));
        const token2 = rotated.url!.split("/").at(-1)!;
        await pool.query("UPDATE tasks SET archived_at=NOW() WHERE id=$1", [root]);
        await pool.query("UPDATE tasks SET archived_at=NULL WHERE id=$1", [root]);
        await assert.rejects(getPublicTaskWorkspace(token2, "https://taskboard.test"));
        // A subtask is shared through its task, never on its own.
        assert.equal((await manageTaskShare(user, child, "status")).allowed, false, "Share the task, not a subtask");
        assert.equal((await manageTaskShare(user, child, "create")).url, undefined);
        assert.equal((await pool.query("SELECT 1 FROM task_public_shares WHERE task_id=$1", [child])).rowCount, 0);
        const live = await manageTaskShare(user, root, "create"), token3 = live.url!.split("/").at(-1)!;
        await pool.query("UPDATE users SET is_disabled=true WHERE id=$1", [owner]);
        await assert.rejects(getPublicTaskWorkspace(token3, "https://taskboard.test"));
        await pool.query("UPDATE users SET is_disabled=false WHERE id=$1", [owner]);
        await manageTaskShare(user, root, "disable");
        await assert.rejects(getPublicTaskFile(token3, "task", fileId));
        await pool.query("INSERT INTO teams(id,name) VALUES($1,'Share test team')", [team]);
        await pool.query("INSERT INTO team_members(team_id,user_id,role) VALUES($1,$2,'manager'),($1,$3,'member')", [team, teamManager, teamEditor]);
        await pool.query("INSERT INTO boards(id,board_type,owner_team_id,team_member_default_access,title) VALUES($1,'team',$2,'editor','Team share')", [teamBoard, team]);
        const teamTask = randomUUID();
        await task(teamTask, null, "Team task", teamBoard);
        assert.equal((await manageTaskShare({ ...user, id: teamManager }, teamTask, "status")).allowed, true);
        assert.equal((await manageTaskShare({ ...user, id: teamEditor }, teamTask, "status")).allowed, false);
        assert.equal((await manageTaskShare({ ...user, id: admin, role: "admin" }, teamTask, "status")).allowed, false);
        process.env.TASKBOARD_PUBLIC_SHARES_ENABLED = "false";
        await assert.rejects(getPublicTaskWorkspace(token3, "https://taskboard.test"));
    }
    finally {
        process.chdir(cwd);
        process.env.TASKBOARD_PUBLIC_SHARES_ENABLED = "true";
        await pool.query("DELETE FROM notes WHERE owner_user_id=ANY($1::uuid[])", [[owner, other, admin, teamManager, teamEditor]]);
        await pool.query("DELETE FROM boards WHERE id=ANY($1::uuid[])", [[board, foreignBoard, teamBoard]]);
        await pool.query("DELETE FROM teams WHERE id=$1", [team]);
        await pool.query("DELETE FROM users WHERE id=ANY($1::uuid[])", [[owner, other, admin, teamManager, teamEditor]]);
        assert.ok(path.resolve(temp).startsWith(path.resolve(os.tmpdir()) + path.sep));
        await rm(temp, { recursive: true, force: true });
        await pool.end();
    }
});
